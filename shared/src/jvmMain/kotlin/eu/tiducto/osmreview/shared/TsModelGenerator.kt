@OptIn(ExperimentalSerializationApi::class)
class TsModelGenerator {
    private val roots = mutableListOf<Pair<SerialDescriptor, Boolean>>()
    private val inputTypes = HashSet<String>()
    private val descriptors = LinkedHashMap<String, SerialDescriptor>()

    fun addResponse(serializer: KSerializer<*>) {
        roots += serializer.descriptor to false
    }

    fun addRequest(serializer: KSerializer<*>) {
        roots += serializer.descriptor to true
    }

    fun render(): String {
        val queue = ArrayDeque(roots)
        while (queue.isNotEmpty()) {
            val (d, input) = queue.removeFirst()
            val name = tsName(d)
            val seen = name in descriptors
            if (seen && (!input || name in inputTypes)) continue
            descriptors[name] = d
            if (input) inputTypes += name
            children(d).forEach { queue += it to input }
        }
        val out = LinkedHashMap<String, String>()
        descriptors.forEach { (name, d) ->
            when (d.kind) {
                SerialKind.ENUM -> out[name] =
                    "export type $name = ${(0 until d.elementsCount).joinToString(" | ") { "'${d.getElementName(it)}'" }}"
                is PolymorphicKind -> {
                    val subs = sealedSubclasses(d)
                    subs.forEach { sub -> out[name + tsName(sub)] = renderClass(sub, name + tsName(sub), sub.serialName, false) }
                    out[name] = "export type $name = ${subs.joinToString(" | ") { name + tsName(it) }}"
                }
                else -> if (!isSealedSubclass(d)) out[name] = renderClass(d, name, null, name in inputTypes)
            }
        }
        return buildString {
            appendLine("// Generated by :shared:generateTsModels from the Kotlin @Serializable models. Do not edit.")
            appendLine()
            append("export type JsonValue = unknown")
            out.values.forEach { appendLine(); appendLine(); append(it) }
            appendLine()
        }
    }

    private fun isSealedSubclass(d: SerialDescriptor): Boolean = descriptors.values.any { parent ->
        parent.kind is PolymorphicKind && sealedSubclasses(parent).any { it.serialName == d.serialName }
    }

    private fun sealedSubclasses(d: SerialDescriptor): List<SerialDescriptor> =
        d.getElementDescriptor(1).elementDescriptors.toList()

    private fun children(d: SerialDescriptor): List<SerialDescriptor> = when (d.kind) {
        is PolymorphicKind -> sealedSubclasses(d).flatMap { sub -> (0 until sub.elementsCount).flatMap { named(sub.getElementDescriptor(it)) } }
        SerialKind.ENUM -> emptyList()
        else -> (0 until d.elementsCount).flatMap { named(d.getElementDescriptor(it)) }
    }

    private fun named(d: SerialDescriptor): List<SerialDescriptor> = when (d.kind) {
        is PrimitiveKind -> emptyList()
        StructureKind.LIST -> named(d.getElementDescriptor(0))
        StructureKind.MAP -> named(d.getElementDescriptor(1))
        else -> if (d.serialName.startsWith("kotlinx.serialization.json.")) emptyList() else listOf(d.nonNullOriginal)
    }

    private fun renderClass(d: SerialDescriptor, name: String, discriminator: String?, input: Boolean): String =
        buildString {
            appendLine("export interface $name {")
            if (discriminator != null) appendLine("  type: '$discriminator'")
            for (i in 0 until d.elementsCount) {
                val opt = if (input && d.isElementOptional(i)) "?" else ""
                appendLine("  ${d.getElementName(i)}$opt: ${tsType(d.getElementDescriptor(i))}")
            }
            append("}")
        }

    private fun tsType(d: SerialDescriptor): String {
        val base = when (d.kind) {
            PrimitiveKind.STRING, PrimitiveKind.CHAR -> "string"
            PrimitiveKind.BOOLEAN -> "boolean"
            is PrimitiveKind -> "number"
            StructureKind.LIST -> tsType(d.getElementDescriptor(0)).let { if (' ' in it) "($it)[]" else "$it[]" }
            StructureKind.MAP -> "Record<string, ${tsType(d.getElementDescriptor(1))}>"
            else -> if (d.serialName.startsWith("kotlinx.serialization.json.")) "JsonValue" else tsName(d)
        }
        return if (d.isNullable) "$base | null" else base
    }

    private fun tsName(d: SerialDescriptor): String =
        d.serialName.removeSuffix("?").substringAfterLast('.').let {
            if ('_' in it) it.split('_').joinToString("") { p -> p.replaceFirstChar(Char::uppercase) } else it
        }
}

fun main(args: Array<String>) {
    val gen = TsModelGenerator()
    listOf(
        serializer<Draft>(), serializer<DraftDetail>(), serializer<Change>(), serializer<Review>(),
        serializer<Rule>(), serializer<Issue>(), serializer<RuleRunResult>(), serializer<Area>(),
        serializer<FeatureCollection>(), serializer<ProposalResult>(), serializer<MergePreview>(),
        serializer<MergeProgress>(), serializer<Upload>(), serializer<AppStatus>(), serializer<ImagerySource>(),
        serializer<UiEvent>(), serializer<ApiError>(), serializer<SearchHit>(), serializer<EditorLinks>(), serializer<AccountStatus>(), serializer<McpInfo>(),
        serializer<OsmChangeImportResult>(),
        serializer<RuleFileList>(), serializer<RuleFileContent>(), serializer<ValidateRuleFileResult>(), serializer<WriteRuleFileResult>(),
        serializer<DeleteRuleFileResult>(), serializer<RuleSource>(),
        serializer<ResolvedPreset>(), serializer<PresetSummary>(), serializer<PresetMatch>(), serializer<PresetApplyResult>(), serializer<PresetBulkApplyResult>(),
        serializer<IdSchemaInfo>(), serializer<SmartPreset>(), serializer<Preset>(),
        serializer<HighlightList>(), serializer<HighlightEvaluation>(), serializer<CoverageStats>(),
        serializer<Scan>(), serializer<ScanReport>(), serializer<ScanDiff>(), serializer<ScanIssue>(), serializer<ScanDraftResult>(),
    ).forEach(gen::addResponse)
    listOf(
        serializer<CreateDraftRequest>(), serializer<DraftFromRuleRequest>(), serializer<RuleIssuesRequest>(), serializer<ProposeChangesRequest>(),
        serializer<ReviewRequest>(), serializer<ResolveConflictRequest>(), serializer<ManualEditRequest>(),
        serializer<UpdateDraftRequest>(), serializer<SetTargetRequest>(), serializer<OsmChangeImportRequest>(), serializer<DraftFromOsmChangeRequest>(),
        serializer<WriteRuleFileRequest>(), serializer<CreateRuleFileRequest>(), serializer<ValidateRuleFileRequest>(),
        serializer<PresetMatchRequest>(), serializer<PresetApplyRequest>(), serializer<ImportPresetRequest>(), serializer<DetachPresetRequest>(), serializer<PresetBulkApplyRequest>(),
        serializer<RunScanRequest>(), serializer<ScanDraftRequest>(), serializer<HighlightStatsRequest>(),
    ).forEach(gen::addRequest)
    val out = File(args.firstOrNull() ?: "models.ts")
    out.parentFile.mkdirs()
    out.writeText(gen.render())
    println("Wrote ${out.path}")
}
