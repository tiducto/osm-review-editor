const dicts: Record<Locale, Dict> = { en, cs }

export function registerStrings(locale: Locale, strings: Dict) {
  Object.assign(dicts[locale], strings)
}

export function tr(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  let s = dicts[locale][key] ?? dicts.en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}
